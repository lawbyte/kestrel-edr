//! JSON-with-comments handling for Windows Terminal `settings.json`.
//!
//! Verified against microsoft/terminal sources: the global key is
//! `"warning.multiLinePaste"` with values `"automatic" | "always" | "never"`
//! (MTSMSettings.h / TerminalSettingsSerializationHelpers.h); the legacy key
//! `"multiLinePasteWarning"` (bool, true→automatic, false→never) is still read
//! by `GlobalAppSettings::LayerJson` *after* the new key, so it must be removed
//! or it overrides ours. It is a global (root-level) setting, not per profile.

use serde_json::{Map, Value};

pub const KEY: &str = "warning.multiLinePaste";
pub const LEGACY_KEY: &str = "multiLinePasteWarning";

/// Remove `//` and `/* */` comments and trailing commas so serde_json can parse.
pub fn strip_jsonc(src: &str) -> String {
    let src = src.trim_start_matches('\u{feff}');
    let b = src.as_bytes();
    let mut out = String::with_capacity(src.len());
    let mut i = 0;
    let mut in_str = false;
    while i < b.len() {
        let c = b[i];
        if in_str {
            // Copy whole UTF-8 sequences.
            let ch = src[i..].chars().next().unwrap_or('\u{fffd}');
            out.push(ch);
            if c == b'\\' && i + 1 < b.len() {
                let next = src[i + 1..].chars().next().unwrap_or('\u{fffd}');
                out.push(next);
                i += 1 + next.len_utf8();
                continue;
            }
            if c == b'"' {
                in_str = false;
            }
            i += ch.len_utf8();
            continue;
        }
        if c == b'"' {
            in_str = true;
            out.push('"');
            i += 1;
            continue;
        }
        if c == b'/' && i + 1 < b.len() && b[i + 1] == b'/' {
            while i < b.len() && b[i] != b'\n' {
                i += 1;
            }
            continue;
        }
        if c == b'/' && i + 1 < b.len() && b[i + 1] == b'*' {
            i += 2;
            while i + 1 < b.len() && !(b[i] == b'*' && b[i + 1] == b'/') {
                i += 1;
            }
            i = (i + 2).min(b.len());
            continue;
        }
        let ch = src[i..].chars().next().unwrap_or('\u{fffd}');
        out.push(ch);
        i += ch.len_utf8();
    }
    remove_trailing_commas(&out)
}

fn remove_trailing_commas(s: &str) -> String {
    let chars: Vec<char> = s.chars().collect();
    let mut out = String::with_capacity(s.len());
    let mut in_str = false;
    let mut i = 0;
    while i < chars.len() {
        let c = chars[i];
        if in_str {
            out.push(c);
            if c == '\\' && i + 1 < chars.len() {
                out.push(chars[i + 1]);
                i += 2;
                continue;
            }
            if c == '"' {
                in_str = false;
            }
            i += 1;
            continue;
        }
        if c == '"' {
            in_str = true;
        }
        if c == ',' {
            let mut j = i + 1;
            while j < chars.len() && chars[j].is_whitespace() {
                j += 1;
            }
            if j < chars.len() && (chars[j] == '}' || chars[j] == ']') {
                i += 1;
                continue;
            }
        }
        out.push(c);
        i += 1;
    }
    out
}

pub fn parse_settings(src: &str) -> Result<Map<String, Value>, String> {
    match serde_json::from_str::<Value>(&strip_jsonc(src)) {
        Ok(Value::Object(m)) => Ok(m),
        Ok(_) => Err("settings.json root is not an object".into()),
        Err(e) => Err(format!("settings.json parse error: {e}")),
    }
}

/// True when the multi-line paste warning is forced on ("always").
pub fn paste_warning_in_effect(src: &str) -> bool {
    match parse_settings(src) {
        Ok(m) => {
            m.get(KEY).and_then(Value::as_str) == Some("always") && !m.contains_key(LEGACY_KEY)
        }
        Err(_) => false,
    }
}

/// Returns the rewritten file, or None when already compliant. Comments in
/// the original are not preserved (callers keep a backup copy).
pub fn enforce_paste_warning(src: &str) -> Result<Option<String>, String> {
    if paste_warning_in_effect(src) {
        return Ok(None);
    }
    let mut m = if src.trim().is_empty() {
        Map::new()
    } else {
        parse_settings(src)?
    };
    m.remove(LEGACY_KEY);
    m.insert(KEY.to_string(), Value::String("always".into()));
    serde_json::to_string_pretty(&Value::Object(m))
        .map(Some)
        .map_err(|e| e.to_string())
}

#[cfg(test)]
mod tests {
    use super::*;

    const SAMPLE: &str = "\u{feff}// This file was initially generated by Windows Terminal\n{\n  \"$schema\": \"https://aka.ms/terminal-profiles-schema\", // trailing comment\n  /* block\n comment */\n  \"multiLinePasteWarning\": false,\n  \"profiles\": { \"list\": [ { \"name\": \"PowerShell // not a comment\", \"commandline\": \"pwsh.exe /* nope */\", }, ], },\n}\n";

    #[test]
    fn strips_comments_not_strings() {
        let m = parse_settings(SAMPLE).unwrap();
        assert_eq!(
            m["profiles"]["list"][0]["name"],
            "PowerShell // not a comment"
        );
        assert_eq!(
            m["profiles"]["list"][0]["commandline"],
            "pwsh.exe /* nope */"
        );
        assert_eq!(m[LEGACY_KEY], false);
    }

    #[test]
    fn enforce() {
        assert!(!paste_warning_in_effect(SAMPLE));
        let out = enforce_paste_warning(SAMPLE).unwrap().unwrap();
        assert!(paste_warning_in_effect(&out));
        let m = parse_settings(&out).unwrap();
        assert!(!m.contains_key(LEGACY_KEY));
        assert_eq!(
            m["profiles"]["list"][0]["name"],
            "PowerShell // not a comment"
        );
        assert_eq!(enforce_paste_warning(&out).unwrap(), None);
        let fresh = enforce_paste_warning("").unwrap().unwrap();
        assert!(paste_warning_in_effect(&fresh));
        assert!(!paste_warning_in_effect(
            r#"{"warning.multiLinePaste": "automatic"}"#
        ));
        assert!(enforce_paste_warning("[1,2]").is_err());
    }

    #[test]
    fn escapes_and_unicode() {
        let s = r#"{"a": "q\"//x", "b": "é/*", /* c */ "c": [1,2,],}"#;
        let m = parse_settings(s).unwrap();
        assert_eq!(m["a"], "q\"//x");
        assert_eq!(m["b"], "é/*");
        assert_eq!(m["c"].as_array().unwrap().len(), 2);
    }
}
